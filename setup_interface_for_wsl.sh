#!/bin/bash

IP_ADDR="192.168.0.100"
NETMASK="255.255.255.0"
MTU=4000

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)

# ── Jumbo-frame ax88179_178a.ko: install the build stored for this kernel (ko/<uname -r>/) ──
# ko_apply picks ko/$(uname -r)/ax88179_178a.ko, verifies its symbol CRCs against the running
# kernel, installs it and reloads the driver. Without a matching build it keeps the stock driver.
# New kernel after a WSL update?  Run ./build_ko.sh inside WSL (as your normal user) once.
# shellcheck source=ko/ko_lib.sh
. "$SCRIPT_DIR/ko/ko_lib.sh"
ko_apply || echo "WARNING: jumbo-frame ax88179_178a.ko not applied; continuing with the stock driver (MTU 1500)."

MISSING_PKGS=""
command -v lsusb >/dev/null 2>&1 || MISSING_PKGS="$MISSING_PKGS usbutils"
command -v ifconfig >/dev/null 2>&1 || MISSING_PKGS="$MISSING_PKGS net-tools"

if [ -n "$MISSING_PKGS" ]; then
    echo "Installing missing packages:$MISSING_PKGS ..."
    sudo apt update
    sudo apt install -y $MISSING_PKGS
else
    echo "usbutils and net-tools already installed. Skipping apt install."
fi

# ── udev rules for USB devices (allows non-root USB access) ──
# Generated from devices.psd1: one rule set per vendor ID found there, so the list of
# devices lives in a single place. Rules match on the vendor ID only, because a probe
# family (J-Link, ST-Link, ...) ships under several product IDs and you normally list just one.
DEVICES_FILE="$SCRIPT_DIR/devices.psd1"
UDEV_RULE="/etc/udev/rules.d/99-usbipd-devices.rules"

if [ ! -r "$DEVICES_FILE" ]; then
    echo "WARNING: $DEVICES_FILE not found; udev rules not updated."
else
    echo "Generating udev rules from $DEVICES_FILE -> $UDEV_RULE ..."
    # Each entry in devices.psd1 is one line:  @{ Name = "..."; VidPid = "vvvv:pppp" },
    # -> "name|vvvv" per line, vendors deduplicated with names joined, order of first appearance kept.
    RULES=$(tr -d '\r' < "$DEVICES_FILE" |
        sed -nE 's/.*Name[[:space:]]*=[[:space:]]*"([^"]*)".*VidPid[[:space:]]*=[[:space:]]*"([0-9A-Fa-f]{4}):[0-9A-Fa-f]{4}".*/\1|\2/p' |
        awk -F'|' '
            { vid = tolower($2)
              if (!(vid in names)) { order[++n] = vid; names[vid] = $1 } else { names[vid] = names[vid] ", " $1 } }
            END {
              print "# Generated by setup_interface_for_wsl.sh from devices.psd1 - do not edit, edit devices.psd1 instead."
              for (i = 1; i <= n; i++) {
                vid = order[i]
                print ""
                print "# " names[vid] " (vendor " vid ")"
                print "SUBSYSTEM==\"usb\", ATTR{idVendor}==\"" vid "\", MODE=\"0666\", GROUP=\"plugdev\""
                print "# " names[vid] " (CDC / serial port)"
                print "SUBSYSTEM==\"tty\", ATTRS{idVendor}==\"" vid "\", MODE=\"0666\", GROUP=\"plugdev\""
              }
            }')
    if ! printf '%s\n' "$RULES" | grep -q '^SUBSYSTEM=='; then
        echo "WARNING: no devices parsed from $DEVICES_FILE; udev rules not updated."
    else
        printf '%s\n' "$RULES" | sudo tee "$UDEV_RULE" > /dev/null
        printf '%s\n' "$RULES" | grep -c '^# .* (vendor ' | xargs -I{} echo "  {} vendor ID(s) written."
    fi
fi

sudo udevadm control --reload-rules
sudo udevadm trigger
echo "udev rules installed."

# Find enx* interface
IFACE=$(ip -o link show | grep -o 'enx[^:@]*' | head -n 1)

if [ -z "$IFACE" ]; then
    echo "WARNING: No enx* interface found. Skipping network configuration."
    echo ""
    echo "Done (udev rules only)."
    exit 0
fi

echo "Found interface: $IFACE"

echo "Bringing interface down to change MTU..."
sudo ip link set dev "$IFACE" down

echo "Setting MTU $MTU..."
MTU_ERR=$(sudo ip link set dev "$IFACE" mtu "$MTU" 2>&1)
MTU_RC=$?
if [ $MTU_RC -ne 0 ]; then
    echo "ERROR: Failed to set MTU $MTU (exit $MTU_RC): $MTU_ERR"
fi

echo "Setting IP address $IP_ADDR and bringing interface up..."
sudo ifconfig "$IFACE" "$IP_ADDR" netmask "$NETMASK" up

ACTUAL_MTU=$(cat "/sys/class/net/$IFACE/mtu" 2>/dev/null)
if [ "$ACTUAL_MTU" != "$MTU" ]; then
    echo ""
    echo "WARNING: Requested MTU $MTU but interface reports $ACTUAL_MTU."
    echo "Driver-reported limits for $IFACE:"
    ip -d link show "$IFACE" | grep -o 'maxmtu [0-9]*'

    USB_DEV_DIR=$(dirname "$(readlink -f "/sys/class/net/$IFACE/device")")
    LINK_SPEED=$(cat "$USB_DEV_DIR/speed" 2>/dev/null)
    echo "Negotiated USB link speed as seen inside WSL: ${LINK_SPEED:-unknown} Mbps (5000 = USB 3.0 SuperSpeed, 480 = USB 2.0 High-Speed)"

    echo "The stock ax88179_178a driver is limited to MTU 1500: usbnet clamps max_mtu to hard_mtu unless the driver sets FLAG_NOMAXMTU."
    echo "A patched build is needed for this kernel ($(uname -r)). Inside WSL, as your normal user, run:"
    echo "    $SCRIPT_DIR/build_ko.sh"
    echo "then run this setup again (or: sudo $SCRIPT_DIR/ko/ko_lib.sh apply)."
fi

echo ""
echo "Done. Current status:"
ip addr show "$IFACE"
